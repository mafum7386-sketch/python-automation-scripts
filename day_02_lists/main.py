# 1. قائمة طلبات بأسعارها
orders = [
    {"item": "Laptop", "price": 800},
    {"item": "Headphones", "price": 50},
    {"item": "Phone", "price": 400}
]

# إضافة عنصر جديد بالـ append
orders.append({"item": "Mouse", "price": 20})

# ترتيب القائمة من الأرخص للأغلى
orders.sort(key=lambda x: x["price"])

print("--- الطلبات مرتبة حسب السعر ---")
for o in orders:
    print(o["item"], "->", o["price"], "$")

# 2. تنظيف قائمة من العناصر المكررة
items = ["Laptop", "Phone", "Laptop", "Mouse", "Phone"]
unique_items = list(set(items))

print("\n--- الأجهزة بدون تكرار ---")
print(unique_items)

